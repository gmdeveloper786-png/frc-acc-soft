<?php

namespace App\Http\Requests;

use App\Enums\AccountLevel;
use App\Enums\AccountType;
use App\Enums\FinancialAccountType;
use App\Enums\FinancialStatement;
use App\Enums\NormalBalance;
use Illuminate\Contracts\Validation\ValidationRule;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class StoreAccountRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     */
    public function authorize(): bool
    {
        return $this->user()?->can('accounts.create') === true;
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, ValidationRule|array<mixed>|string>
     */
    public function rules(): array
    {
        // Add Account: the server derives the code, classification and defaults from the parent,
        // so a request that tries to set them is refused instead of silently ignored.
        return [
            'account_type' => ['required', Rule::enum(AccountType::class)],
            'level' => ['required', Rule::in([AccountLevel::Group->value, AccountLevel::SubGroup->value, AccountLevel::Ledger->value])],
            'parent_id' => ['required', 'integer', 'exists:accounts,id'],
            'name' => ['required', 'string', 'max:255'],
            'description' => ['nullable', 'string', 'max:2000'],
            'is_contra' => ['sometimes', 'boolean'],
            'is_postable' => ['sometimes', 'boolean'],
            'financial_account_type' => ['nullable', Rule::enum(FinancialAccountType::class)],
            'purchase_bill_debit_eligible' => ['sometimes', 'boolean'],
            'code' => ['prohibited'],
            'normal_balance' => ['prohibited'],
            'financial_statement' => ['prohibited'],
            'is_active' => ['prohibited'],
            'sort_order' => ['prohibited'],
        ];
    }

    public function messages(): array
    {
        return [
            'code.prohibited' => 'Account codes are generated by the system.',
            'level.in' => 'The five account classes are fixed. Choose Group, Sub Group or Ledger.',
        ];
    }

    protected function accountRules(): array
    {
        return [
            'code' => ['required', 'string', 'max:50', 'regex:/^[A-Za-z0-9._-]+$/', 'unique:accounts,code'],
            'name' => ['required', 'string', 'max:255'],
            'parent_id' => ['nullable', 'integer', 'exists:accounts,id'],
            'account_type' => ['required', Rule::enum(AccountType::class)],
            'level' => ['required', Rule::enum(AccountLevel::class)],
            'normal_balance' => ['required', Rule::enum(NormalBalance::class)],
            'financial_statement' => ['required', Rule::enum(FinancialStatement::class)],
            'financial_account_type' => ['nullable', Rule::enum(FinancialAccountType::class)],
            'purchase_bill_debit_eligible' => ['sometimes', 'boolean'],
            'direct_payment_eligible' => ['sometimes', 'boolean'],
            'is_postable' => ['required', 'boolean'],
            'is_active' => ['required', 'boolean'],
            'description' => ['nullable', 'string', 'max:2000'],
            'sort_order' => ['nullable', 'integer', 'min:0', 'max:1000000'],
        ];
    }
}
